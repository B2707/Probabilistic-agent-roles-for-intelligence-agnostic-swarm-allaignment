"""Copy finished runs from runs/ (git-ignored) into results/ (in git), rebuild results/metrics.md, and push.

Usage, from the repo root:  uv run python scripts/publish_results.py [--push]

- v2 runs (their config has `pr_approvals`) that have ended go to results/<run>/. Runs stopped by hand
  (folder name ends in -stopped) go to results/stopped/<run>/ and stay out of the metrics table.
- Runs that started each round's turns in agent id order (no `shuffle_turns`) go to results/ordered/<run>/, with their
  own table in results/ordered/metrics.md. They are archived: the 8 Nov reruns with shuffled turns replace them.
- The tables are built from results/*/metrics.json, so they include runs another machine published. With --push,
  pull before pushing (scripts/gitpush.py) and rebuild the tables after the pull.
- The v1 pilots that data/audit_truth.json refers to go to results/v1/<run>/, so auditor-eval can run.
- Per run: config, events, world state, judge labels and the judge prompt used, metrics, reaudit files,
  the frozen prompts, and the run and label logs. Not copied: the task repo (its own git history),
  Codex working folders and hidden test copies.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS, OUT = ROOT / "runs", ROOT / "results"
FILES = ("config.json", "events.jsonl", "world.json", "labels.jsonl", "labels.v0.jsonl", "labels.judge.md",
         "metrics.json")

sys.path.insert(0, str(ROOT))
from swarm.metrics import compute_run, model_table, table  # noqa: E402
from gitpush import commit_and_push  # noqa: E402


# Disclosed extras: listed in the table, left out of the MEAN rows. The first seed-1 v3 runs hit the 7 Nov 23:21 freeze
# and 403 stops and ran without Fast mode; the clean rerun (*-6-luna-s1fast) is seed 1 (Bader, 8 Nov 03:00).
EXTRAS = {"A100-6-luna-20261107-230001", "B100-6-luna-20261107-230001", "C100-6-luna-20261107-230001"}


def ended(run: Path) -> bool:
    events = run / "events.jsonl"
    return events.exists() and any(json.loads(l)["type"] == "run_end" for l in events.read_text().splitlines()[-50:]
                                   if l.strip())


def copy_run(run: Path, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    for name in FILES:
        if (run / name).exists():
            shutil.copy2(run / name, dest / name)
    for f in run.glob("reaudit-*.jsonl"):
        shutil.copy2(f, dest / f.name)
    if (run / "prompts").is_dir():
        shutil.copytree(run / "prompts", dest / "prompts", dirs_exist_ok=True)
    for suffix in (".log", ".label.log"):
        log = run.with_name(run.name + suffix)
        if log.exists():
            shutil.copy2(log, dest / f"run{suffix}")


def dest(run: Path, cfg: dict) -> Path:
    if run.name.endswith("-stopped"):
        return OUT / "stopped" / run.name
    if not cfg.get("shuffle_turns"):
        return OUT / "ordered" / run.name
    return OUT / run.name


def write_tables() -> None:
    """Rebuild both tables from the published metrics.json files, whichever machine published them."""
    def rows(folder: Path) -> list[dict]:
        return [{**json.loads(f.read_text()), "folder": f.parent.name, "extra": f.parent.name in EXTRAS}
                for f in sorted(folder.glob("*/metrics.json"))]
    (OUT / "metrics.md").write_text(
        "# Metrics: production runs\n\nGenerated by `scripts/publish_results.py` from `results/<run>/metrics.json`, "
        "from every machine that runs arms. Runs without judge labels show `labels_present` False. Runs whose turns "
        "started in agent id order are archived in `results/ordered/metrics.md`. A MEAN row averages only the arm's runs "
        "that completed, and leaves out disclosed extras, marked `(extra)`: the first seed-1 runs, which the 7 Nov 23:21 "
        "freeze and 403 stops disturbed.\n\n" + table(rows(OUT)) + "\n"
        + (f"\n## Mixed swarms by worker model\n\n{split}\n" if (split := model_table(rows(OUT))) else ""))
    ordered = rows(OUT / "ordered")
    if ordered:
        (OUT / "ordered" / "metrics.md").write_text(
            "# Metrics: archived runs with turns in agent id order\n\nEvery round started its turns in agent id "
            "order, so agents a001 to a010 always went first. Rerun from 8 Nov with `shuffle_turns = true`; the "
            "reruns are in `results/metrics.md`.\n\n" + table(ordered) + "\n")


def main() -> int:
    published = []
    for run in sorted(p for p in RUNS.iterdir() if p.is_dir() and (p / "config.json").exists()):
        cfg = json.loads((run / "config.json").read_text())
        if "pr_approvals" not in cfg or not ended(run) and not run.name.endswith("-stopped"):
            continue
        if not run.name.endswith("-stopped"):
            compute_run(run)  # refresh metrics.json with the current labels
        copy_run(run, dest(run, cfg))
        published.append(str(dest(run, cfg).relative_to(OUT)))
    truth = json.loads((ROOT / "data" / "audit_truth.json").read_text())
    for name in truth:
        if (RUNS / name).is_dir():
            copy_run(RUNS / name, OUT / "v1" / name)
            published.append(f"v1/{name}")
    write_tables()
    print("published:", ", ".join(published))
    if "--push" in sys.argv:
        return commit_and_push(ROOT, ["results"], f"Publish results: {len(published)} runs", rebuild=write_tables)
    return 0


if __name__ == "__main__":
    sys.exit(main())
